// Generates supabase/seed.sql from the fictional demo master data in src/data.
// Run: npx tsx scripts/generate-seed-sql.ts
// Synthetic only — never point this at real collector lists or real geometry.
import { writeFileSync } from 'node:fs';
import { DEMO_COLLECTION_AREAS, DEMO_COLLECTORS, DEMO_GROUPS, DEMO_LOCATIONS } from '../src/data/geography';
import { circlePolygon } from '../src/domain/disclosure';
import { areaCentroid } from '../src/domain/engine';

const q = (s: string | null | undefined) => (s == null ? 'null' : `'${String(s).replace(/'/g, "''")}'`);
const j = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;
const kind = (k: string) => k.replace(/-/g, '_');
const out: string[] = [
  '-- SYNTHETIC DEMO MASTER DATA — generated by scripts/generate-seed-sql.ts. All names and geometry are fictional.',
  '-- Users are not seeded here: create them through invitations (see docs/SUPABASE_SETUP.md).',
  'begin;',
];
for (const l of DEMO_LOCATIONS) {
  out.push(
    `insert into public.locations (code, name, kind, lat, lng, public_label, country, account_code, public_place) values (${q(l.id)}, ${q(l.name)}, ${q(kind(l.kind))}, ${l.lat}, ${l.lng}, ${q(l.publicLabel)}, ${q(l.country)}, ${q(l.accountCode)}, ${!!l.publicPlace});`,
  );
}
for (const a of DEMO_COLLECTION_AREAS) {
  const [lng, lat] = areaCentroid(a);
  const pub = circlePolygon(Math.round(lat / 0.25) * 0.25, Math.round(lng / 0.25) * 0.25, 30).map(([x, y]) => [+x.toFixed(5), +y.toFixed(5)]);
  out.push(
    `insert into public.locations (code, name, kind, lat, lng, public_label, country) values (${q(a.id)}, ${q(a.name)}, 'collection_area', ${lat.toFixed(5)}, ${lng.toFixed(5)}, 'Certified forest-reserve collection area', 'Ghana');`,
    `insert into public.collection_areas (location_id, area_code, operational_area, public_polygon) select id, ${q(a.code)}, ${q(a.operationalArea)}, ${j(pub)} from public.locations where code = ${q(a.id)};`,
    `insert into public.collection_area_geometry (location_id, polygon, geometry_source) select id, ${j(a.polygon)}, ${q(a.geometrySource)} from public.locations where code = ${q(a.id)};`,
  );
}
for (const c of DEMO_COLLECTORS) {
  out.push(
    `insert into public.collectors (code, collection_area_id) select ${q(c.code)}, id from public.locations where code = ${q(c.collectionAreaId)};`,
    `insert into public.collector_personal (collector_id, full_name) select id, ${q(c.name)} from public.collectors where code = ${q(c.code)};`,
  );
}
for (const g of DEMO_GROUPS) {
  out.push(`insert into public.processing_groups (code, centre_id, name, members) select ${q(g.id)}, id, ${q(g.name)}, ${g.members} from public.locations where code = ${q(g.centreId)};`);
}
for (const c of ['DEMO Lumière Naturals B.V.', 'DEMO Nordhavn Personal Care A/S']) out.push(`insert into public.clients (name) values (${q(c)});`);
out.push('commit;', '');
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), out.join('\n'), 'utf8');
console.log(`seed.sql: ${out.length} lines`);
